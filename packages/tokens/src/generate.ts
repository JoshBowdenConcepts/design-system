/**
 * Custom token generator (not Style Dictionary).
 *
 * Reads the token source and emits:
 *   - dist/web/tokens.css   CSS custom properties in scoped selector blocks
 *   - dist/ios/DesignSystemTokens/Tokens.swift   Swift constants
 *
 * The typed JS entry (dist/web/index.js + .d.ts) is emitted by `tsc` from
 * src/, so this file only owns the CSS and Swift projections.
 *
 * Output is deterministic: the same source produces byte-identical files.
 */
import { mkdirSync, writeFileSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { breakpoints, tokens } from "./tokens/index.js";
import type { Breakpoints, TokenValue, Tokens } from "./types.js";

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(here, "..");
const webDir = join(pkgRoot, "dist", "web");
const iosDir = join(pkgRoot, "dist", "ios", "DesignSystemTokens");

/** `fontFamily` -> `--ds-font-family`, `color.bg` -> `--ds-color-bg`. */
export function cssVarName(key: string): string {
  return `--ds-${key
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[._]/g, "-")
    .toLowerCase()}`;
}

function decl(key: string, value: TokenValue): string {
  return `  ${cssVarName(key)}: ${value};`;
}

function block(selector: string, lines: string[]): string {
  if (lines.length === 0) return `${selector} {}`;
  return `${selector} {\n${lines.join("\n")}\n}`;
}

export function renderCss(tokenSet: Tokens, bps: Breakpoints): string {
  const entries = Object.entries(tokenSet);
  const blocks: string[] = [];

  // :root defaults (light color mode is the default surface)
  blocks.push(
    block(
      ":root",
      entries.map(([k, t]) => decl(k, t.colorModes?.light ?? t.value)),
    ),
  );

  // breakpoint axis -> @media { :root { ... } }
  for (const [bpName, minWidth] of Object.entries(bps)) {
    const lines = entries
      .filter(([, t]) => t.breakpoints && bpName in t.breakpoints)
      .map(([k, t]) => decl(k, t.breakpoints![bpName]!));
    if (lines.length) {
      blocks.push(
        `@media (min-width: ${minWidth}) {\n  :root {\n  ${lines.join("\n  ")}\n  }\n}`,
      );
    }
  }

  // color-mode axis -> [data-theme="dark"]
  const darkLines = entries
    .filter(([, t]) => t.colorModes?.dark !== undefined)
    .map(([k, t]) => decl(k, t.colorModes!.dark!));
  if (darkLines.length) blocks.push(block('[data-theme="dark"]', darkLines));

  // feature axis -> .ds-feature-<name>
  const features = new Set<string>();
  for (const [, t] of entries)
    for (const f of Object.keys(t.features ?? {})) features.add(f);
  for (const feature of [...features].sort()) {
    const lines = entries
      .filter(([, t]) => t.features && feature in t.features)
      .map(([k, t]) => decl(k, t.features![feature]!));
    blocks.push(block(`.ds-feature-${feature}`, lines));
  }

  return `/* Generated by @design-system/tokens. Do not edit. */\n${blocks.join("\n\n")}\n`;
}

export function renderSwift(tokenSet: Tokens): string {
  const lines = Object.entries(tokenSet).map(([k, t]) => {
    const isNum = typeof t.value === "number";
    const type = isNum ? "Double" : "String";
    const val = isNum ? String(t.value) : JSON.stringify(t.value);
    const doc = t.description ? `    /// ${t.description}\n` : "";
    return `${doc}    public static let ${k}: ${type} = ${val}`;
  });
  const body = lines.length ? `\n${lines.join("\n")}\n` : "\n";
  return `// Generated by @design-system/tokens. Do not edit.\n\npublic enum DesignSystemTokens {${body}}\n`;
}

export function generate(): void {
  // Runs before `tsc`, so it owns the whole dist/ tree.
  rmSync(join(pkgRoot, "dist"), { recursive: true, force: true });
  mkdirSync(webDir, { recursive: true });
  mkdirSync(iosDir, { recursive: true });

  writeFileSync(join(webDir, "tokens.css"), renderCss(tokens, breakpoints), "utf8");
  writeFileSync(join(iosDir, "Tokens.swift"), renderSwift(tokens), "utf8");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  generate();
  const count = Object.keys(tokens).length;
  console.log(`@design-system/tokens: generated CSS + Swift for ${count} token(s)`);
}
